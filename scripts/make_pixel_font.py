def build_pixel_font(font_name="MyCustomPixelFont", output_path="MyCustomPixelFont.ttf", pixel_map_override=None):
    active_map = pixel_map_override if pixel_map_override else PIXEL_MAP
    units_per_em = 1000
    grid_cols = 8
    grid_rows = 8
    pixel_size = units_per_em // grid_rows  # 125 units per pixel
    advance_width = grid_cols * pixel_size   # 1000 units (monospaced)
    baseline_offset = 125                     # Baseline shift

    name_map = {
        " ": "space",
        ".": "period",
        ",": "comma",
        ":": "colon",
        ";": "semicolon",
        "=": "equal",
        "+": "plus",
        "-": "hyphen",
        "*": "asterisk",
        "/": "slash",
        "\\": "backslash",
        "(": "parenleft",
        ")": "parenright",
        "[": "bracketleft",
        "]": "bracketright",
        "{": "braceleft",
        "}": "braceright",
        "<": "less",
        ">": "greater",
        "_": "underscore",
        "!": "exclam",
        "?": "question",
        "#": "numbersign",
        "$": "dollar",
        "%": "percent",
        "&": "ampersand",
        "'": "quotesingle",
        '"': "quotedbl",
        "`": "grave",
        "~": "asciitilde",
        "@": "at",
        "^": "asciicircum",
        "|": "bar",
    }

    glyph_order = [".notdef", ".null", "nonmarkingreturn"]
    cmap = {}
    glyphs = {}

    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    glyphs[".null"] = pen.glyph()
    glyphs["nonmarkingreturn"] = pen.glyph()

    for char, grid in active_map.items():
        gname = name_map.get(char, char)
        glyph_order.append(gname)
        cmap[ord(char)] = gname

        pen = TTGlyphPen(None)
        for row_idx, row_str in enumerate(grid):
            y_top = (grid_rows - row_idx) * pixel_size - baseline_offset
            y_bottom = y_top - pixel_size
            for col_idx, col_char in enumerate(row_str):
                if col_char != " ":
                    x_left = col_idx * pixel_size
                    x_right = x_left + pixel_size
                    pen.moveTo((x_left, y_bottom))
                    pen.lineTo((x_right, y_bottom))
                    pen.lineTo((x_right, y_top))
                    pen.lineTo((x_left, y_top))
                    pen.closePath()

        glyphs[gname] = pen.glyph()

    metrics = {name: (advance_width, 0) for name in glyph_order}

    fb = FontBuilder(units_per_em, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=875, descent=-125)
    fb.setupOS2(sTypoAscender=875, sTypoDescender=-125, usWinAscent=875, usWinDescent=125)
    fb.setupNameTable({
        "familyName": font_name,
        "styleName": "Regular",
        "uniqueFontIdentifier": f"DataStuff:{font_name}:2026",
        "fullName": font_name,
        "version": "Version 1.000",
        "psName": font_name.replace(" ", ""),
    })
    fb.setupPost()
    fb.save(output_path)
    print(f"Successfully generated font: {output_path}")

