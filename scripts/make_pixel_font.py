    import json
    font_name = sys.argv[1] if len(sys.argv) > 1 else "AntigravityPixel"
    out_file = sys.argv[2] if len(sys.argv) > 2 else f"{font_name}.ttf"
    json_path = sys.argv[3] if len(sys.argv) > 3 else None

    pixel_override = None
    if json_path and os.path.exists(json_path):
        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            if "fontName" in data and data["fontName"]:
                font_name = data["fontName"]
            if "pixelMap" in data:
                pixel_override = data["pixelMap"]

    build_pixel_font(font_name, out_file, pixel_map_override=pixel_override)
